using UnityEngine;
using UnityEngine.UIElements;

namespace Lumon.HubWorld
{
    [UxmlElement]
    public partial class LumonPixelGlyph : VisualElement
    {
        private int kind;
        [UxmlAttribute]
        public int Kind { get => kind; set { kind = value; MarkDirtyRepaint(); } }

        public LumonPixelGlyph() { generateVisualContent += Draw; }

        private static readonly string[][] Patterns =
        {
            new[]{"............","....##......","...####.....","..######....",".########...","############",".##......##.",".##..o...##.",".##..o...##.",".##########.","............","............"},
            new[]{"............",".....##.....","....####....","...######...","..##o.o##...","..##...##...","..##...##...","...######...","....####....","............","............","............"},
            new[]{"............","....##......","...####.....","..##..##....","..#.##.##...","..##..##....","...####.....","....##......","...######...","..########..","............","............"},
            new[]{".....##.....","..#..##..#..","...#.##.#...","....####....",".##########.","....####....","...#.##.#...","..#..##..#..",".....##.....","............","............","............"},
            new[]{"............","............","..########..","..########..","..########..",".....##.....",".....##.....",".....##.....",".....##.....",".....##.....","............","............"},
            new[]{"..########..","..##......#.","..##..##..#.","..##..##..#.","..#########.","..##........","..##........","..##........","............","............","............","............"},
            new[]{"....####....","..########..",".##..##..##.",".##..##..##.",".##########.",".##..##..##.",".##..##..##.","..########..","....####....","............","............","............"},
            new[]{"....####....","...######...","..##....##..","..##....##..","..##....##..","...######...","....####....","............","............","............","............","............"},
            new[]{".....##.....","....####....","...##..##...","..##..o.##..","..#..o...#..","..#..o...#..","..##..o.##..","...##..##...","....####....",".....##.....","............","............"},
            new[]{".....##.....","....####....","...#o##o#...","..##o##o##..","..#o##o##...","..##o##o##..","..#o##o##...","...#o##o#...","....####....",".....##.....","............","............"},
            new[]{"............",".....##.....","..#..##..#..","...#.##.#...","....####....",".##########.",".#####o####.","....####....","...#.##.#...","..#..##..#..",".....##.....","............"},
        };
        private static readonly Color Ink = new(0.87f, 0.75f, 0.58f);
        private static readonly Color Gold = new(0.51f, 0.74f, 0.74f);

        private void Draw(MeshGenerationContext context)
        {
            if (contentRect.width < 4 || contentRect.height < 4) return;
            string[] pattern = Patterns[Mathf.Abs(kind) % Patterns.Length];
            float cell = Mathf.Max(1, Mathf.Floor(Mathf.Min(contentRect.width, contentRect.height) / 12f));
            float ox = Mathf.Floor((contentRect.width - cell * 12) * 0.5f);
            float oy = Mathf.Floor((contentRect.height - cell * 12) * 0.5f);
            var p = context.painter2D;
            for (int y = 0; y < 12; y++) for (int x = 0; x < 12; x++)
            {
                if (pattern[y][x] == '.') continue;
                p.fillColor = pattern[y][x] == 'o' ? Gold : Ink;
                p.BeginPath();
                p.MoveTo(new Vector2(ox + x * cell, oy + y * cell));
                p.LineTo(new Vector2(ox + (x + 1) * cell, oy + y * cell));
                p.LineTo(new Vector2(ox + (x + 1) * cell, oy + (y + 1) * cell));
                p.LineTo(new Vector2(ox + x * cell, oy + (y + 1) * cell));
                p.ClosePath(); p.Fill();
            }
        }
    }
}
